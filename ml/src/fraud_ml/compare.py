"""Compare evaluation runs side by side.

Reads every ``reports/runs/<run>/metrics.json`` and writes
``reports/comparison.md``. Decisions about features and parameters are made
on the **validation** columns; test columns are shown so the final result
is visible, not to choose between runs.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from fraud_ml.config import load_params

REVIEW_RATE = 0.01  # the review rate shown in the summary table


def _recall_at(model: dict, rate: float) -> str:
    for row in model["at_review_rate"]:
        if abs(row["review_rate"] - rate) < 1e-9:
            return f"{row['recall']:.3f}"
    return "n/a"


def compare(reports_dir: Path) -> Path:
    """Write the comparison table and return its path.

    Raises:
        FileNotFoundError: If no runs exist yet.
    """
    runs = sorted(
        (json.loads(path.read_text()) for path in (reports_dir / "runs").glob("*/metrics.json")),
        key=lambda result: result["run"],
    )
    if not runs:
        raise FileNotFoundError(f"no runs under {reports_dir / 'runs'}; run make evaluate first")
    lines = [
        "# Run comparison",
        "",
        "Generated by `make compare`; do not edit by hand. Choose between runs on the",
        "validation columns; test columns report the final result of each run.",
        "",
        f"| Run | Model | Valid PR-AUC | Valid ROC-AUC | Valid recall @{REVIEW_RATE:.0%} "
        f"| Test PR-AUC | Test ROC-AUC | Test recall @{REVIEW_RATE:.0%} | Code |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for result in runs:
        valid, test = result["ranges"]["valid"]["models"], result["ranges"]["test"]["models"]
        for name in valid:
            lines.append(
                f"| {result['run']} | {name} | {valid[name]['pr_auc']:.4f} | "
                f"{valid[name]['roc_auc']:.4f} | {_recall_at(valid[name], REVIEW_RATE)} | "
                f"{test[name]['pr_auc']:.4f} | {test[name]['roc_auc']:.4f} | "
                f"{_recall_at(test[name], REVIEW_RATE)} | `{result['code']['commit'][:7]}` |"
            )
    path = reports_dir / "comparison.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def main() -> None:
    """Command-line entry point: ``python -m fraud_ml.compare``."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--params", type=Path, default=Path("params.yaml"))
    args = parser.parse_args()
    print(f"wrote {compare(load_params(args.params).data.reports_dir)}")


if __name__ == "__main__":
    main()
