"""Tune LightGBM on the validation range and measure seed noise.

Reads only the train and validation ranges; the test range is never loaded,
so tuning cannot leak into the reported result (dataset card, leakage rule
4). The baseline is not tuned: it is a fixed reference.

Two studies:

1. **Grid:** every combination in ``tuning.grid`` is trained once with the
   current seed and scored by validation PR-AUC.
2. **Seed noise:** the current settings and the best grid point are each
   retrained with every seed in ``tuning.seeds``. The spread across seeds
   tells how large a difference must be before it means anything.

Caveat: early stopping also uses the validation range, so validation scores
here are slightly optimistic. That is acceptable for ranking settings; the
untouched test range gives the unbiased number.

The stage writes ``reports/tuning/tuning.json`` and ``tuning.md`` and does
not edit ``params.yaml``: choosing values stays a recorded human decision.
"""

from __future__ import annotations

import argparse
import itertools
import json
import statistics
import time
from dataclasses import asdict, replace
from pathlib import Path

from fraud_ml import manifest, metrics
from fraud_ml.config import Params, load_params
from fraud_ml.data import LABEL
from fraud_ml.train import fit_lightgbm, load_prepared


def _score(params: Params, pre, ranges) -> dict:
    started = time.perf_counter()
    booster = fit_lightgbm(ranges["train"], ranges["valid"], pre, params)
    valid = ranges["valid"]
    p = booster.predict(valid[pre.feature_names])
    return {
        "valid_pr_auc": metrics.ranking(valid[LABEL].to_numpy(), p)["pr_auc"],
        "best_iteration": booster.best_iteration,
        "seconds": round(time.perf_counter() - started, 1),
    }


def tune(params: Params) -> Path:
    """Run both studies and return the Markdown report path."""
    pre, ranges = load_prepared(params, ("train", "valid"))
    grid = params.tuning.grid
    names = list(grid)

    grid_results = []
    for values in itertools.product(*(grid[name] for name in names)):
        setting = dict(zip(names, values, strict=True))
        trial = replace(params, lightgbm=replace(params.lightgbm, **setting))
        grid_results.append({"setting": setting, **_score(trial, pre, ranges)})
    best = max(grid_results, key=lambda row: row["valid_pr_auc"])

    candidates = {
        "current": {name: getattr(params.lightgbm, name) for name in names},
        "best_grid": best["setting"],
    }
    seed_results = {}
    for label, setting in candidates.items():
        scores = []
        for seed in params.tuning.seeds:
            trial = replace(params, seed=seed, lightgbm=replace(params.lightgbm, **setting))
            scores.append(_score(trial, pre, ranges)["valid_pr_auc"])
        seed_results[label] = {
            "setting": setting,
            "scores": scores,
            "mean": statistics.fmean(scores),
            "stdev": statistics.stdev(scores) if len(scores) > 1 else 0.0,
        }

    out = params.data.reports_dir / "tuning"
    out.mkdir(parents=True, exist_ok=True)
    result = {
        "code": manifest.code_version(),
        "lightgbm_base": asdict(params.lightgbm),
        "grid": grid_results,
        "seeds": params.tuning.seeds,
        "seed_study": seed_results,
    }
    (out / "tuning.json").write_text(json.dumps(result, indent=2))
    report = out / "tuning.md"
    report.write_text(_render(result, names))
    return report


def _render(result: dict, names: list[str]) -> str:
    lines = [
        "# LightGBM tuning (validation range only)",
        "",
        "Generated by `make tune`; do not edit by hand. The test range is not read.",
        "",
        f"- Code: `{result['code']['commit']}`"
        + (" (dirty tree)" if result["code"]["dirty"] else ""),
        "- Other LightGBM settings: "
        + ", ".join(f"{k}={v}" for k, v in result["lightgbm_base"].items() if k not in names),
        "",
        "## Grid",
        "",
        "| " + " | ".join(names) + " | Valid PR-AUC | Best iteration | Seconds |",
        "|" + "---|" * (len(names) + 3),
    ]
    for row in sorted(result["grid"], key=lambda r: -r["valid_pr_auc"]):
        values = " | ".join(str(row["setting"][n]) for n in names)
        lines.append(
            f"| {values} | {row['valid_pr_auc']:.4f} | {row['best_iteration']} | {row['seconds']} |"
        )
    lines += [
        "",
        f"## Seed noise (seeds {result['seeds']})",
        "",
        "| Candidate | Setting | Mean PR-AUC | Std dev | Scores |",
        "|---|---|---|---|---|",
    ]
    for label, row in result["seed_study"].items():
        setting = ", ".join(f"{k}={v}" for k, v in row["setting"].items())
        scores = ", ".join(f"{s:.4f}" for s in row["scores"])
        lines.append(f"| {label} | {setting} | {row['mean']:.4f} | {row['stdev']:.4f} | {scores} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Command-line entry point: ``python -m fraud_ml.tune``."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--params", type=Path, default=Path("params.yaml"))
    args = parser.parse_args()
    print(f"wrote {tune(load_params(args.params))}")


if __name__ == "__main__":
    main()
